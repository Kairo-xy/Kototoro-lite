#!/usr/bin/env python3
"""Build an arm64 iOS preview in ignored build directories; no global installation or Git operations."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import zipfile
import tempfile
import inspect
import re
import shlex
from importlib.util import module_from_spec, spec_from_file_location

APP = Path(__file__).resolve().parent.parent
ROOT = APP.parent
PINS = json.loads((APP / "Scripts/jvm-preview-pins.json").read_text())
WORK = APP / "build/jvm-work"
OUTPUT = APP / "build/jvm"
TOOLS = APP / "build/tools"
WORK.mkdir(parents=True, exist_ok=True)
OUTPUT.mkdir(parents=True, exist_ok=True)


def run(arguments, cwd=None, env=None):
    print("+", " ".join(str(arg) for arg in arguments), flush=True)
    subprocess.run([str(arg) for arg in arguments], cwd=cwd, env=env, check=True)


def download(name):
    url, expected = PINS["downloads"][name]
    path = WORK / name
    if not path.exists():
        temporary = path.with_suffix(path.suffix + ".download")
        run(["curl", "--fail", "--location", "--retry", "3", "--output", temporary, url])
        temporary.replace(path)
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        raise RuntimeError("SHA-256 mismatch: " + str(path))
    return path


def extract(archive, directory=WORK):
    with tarfile.open(archive) as source:
        members = source.getmembers()
        for member in members:
            target = (directory / member.name).resolve()
            if not target.is_relative_to(directory.resolve()):
                raise RuntimeError("Unsafe archive path: " + member.name)
            if member.issym() or member.islnk():
                link = (target.parent / member.linkname).resolve() if member.issym() else (directory / member.linkname).resolve()
                if not link.is_relative_to(directory.resolve()):
                    raise RuntimeError("Unsafe archive link: " + member.name)
        source.extractall(directory)
        return directory / members[0].name.split("/")[0]


def linker_jdk():
    linker = WORK / "kototoro-linker-jdk"
    linker.mkdir(exist_ok=True)
    homes = list(linker.glob("*/Contents/Home"))
    if not homes:
        extract(download("linker-jdk.tar.gz"), linker)
        homes = list(linker.glob("*/Contents/Home"))
    if len(homes) != 1:
        raise RuntimeError("Expected one pinned linker JDK")
    return homes[0]


def copy_runtime_file(source, destination):
    """Replace generated read-only jlink files atomically without changing their permissions in place."""
    destination = Path(destination)
    descriptor, temporary = tempfile.mkstemp(prefix=destination.name + ".", dir=destination.parent)
    os.close(descriptor)
    try:
        shutil.copy2(source, temporary)
        os.replace(temporary, destination)
    finally:
        if Path(temporary).exists():
            Path(temporary).unlink()
    return destination


def java_image(mobile, build, output):
    """Link only locally built classes and data. A host JDK is a tool, never the iOS java.base provider."""
    tools = linker_jdk() / "bin"
    # The newer host jlink task rejects Mobile's older build metadata. Use the unchanged task from the pinned
    # Mobile source rather than forging metadata or substituting a foreign java.base. Runtime-specific JLI
    # generation is disabled; simulator regression tests verify the generated module image against the Zero VM.
    linker_source = WORK / "kototoro-jlink-source/jdk/tools/jlink/internal/JlinkTask.java"
    linker_source.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(mobile / "src/jdk.jlink/share/classes/jdk/tools/jlink/internal/JlinkTask.java", linker_source)
    linker_classes = WORK / "kototoro-jlink-classes"
    run([tools / "javac", "--patch-module", "jdk.jlink=" + str(WORK / "kototoro-jlink-source"),
         "-d", linker_classes, linker_source])
    modules = ["java.base", "java.xml", "java.logging", "jdk.unsupported", "jdk.localedata", "jdk.charsets"]
    with tempfile.TemporaryDirectory(prefix="java-image-", dir=WORK) as temporary:
        temporary = Path(temporary)
        jmods = temporary / "jmods"
        jmods.mkdir()
        for name in modules:
            # jlink models Darwin as macos-aarch64; no native commands/libraries from that platform enter the image.
            command = [tools / "jmod", "create", "--module-version", "26", "--target-platform", "macos-aarch64",
                       "--class-path", build / "jdk/modules" / name]
            if name == "java.base":
                # tzdb.dat and cacerts are generated by OpenJDK's own gendata targets.
                data = temporary / "base-libs"
                (data / "security").mkdir(parents=True)
                for relative in ["tzdb.dat", "security/cacerts"]:
                    source = build / "jdk/lib" / relative
                    if not source.is_file():
                        raise RuntimeError("Missing OpenJDK runtime data: " + str(source))
                    shutil.copy2(source, data / relative)
                command += ["--config", build / "jdk/conf", "--libs", data]
            legal = mobile / "src" / name / "share/legal"
            if legal.exists():
                command += ["--legal-notices", legal]
            command += [jmods / (name + ".jmod")]
            run(command)
        image = temporary / "image"
        run([tools / "java", "--patch-module", "jdk.jlink=" + str(linker_classes),
             "-m", "jdk.jlink/jdk.tools.jlink.internal.Main", "--module-path", jmods, "--add-modules", ",".join(modules), "--output", image,
             "--no-header-files", "--no-man-pages", "--disable-plugin", "generate-jli-classes"])
        shutil.copytree(image, output / "java_bundle", dirs_exist_ok=True, copy_function=copy_runtime_file)
        shutil.copy2(mobile / "LICENSE", output / "java_bundle/LICENSE")


def build_tool(name, archive_name, env):
    if (TOOLS / "bin" / name).exists():
        return
    source = extract(download(archive_name))
    run(["./configure", "--prefix=" + str(TOOLS)], cwd=source, env=env)
    run(["make", "-j4"], cwd=source, env=env)
    run(["make", "install"], cwd=source, env=env)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=["iphonesimulator", "iphoneos"], default="iphonesimulator")
    parser.add_argument("--profile", type=Path, help="Reuse an already staged runtime's Java libraries and sources")
    arguments = parser.parse_args()
    simulator = arguments.platform == "iphonesimulator"
    output = OUTPUT if simulator else APP / "build/jvm-device"
    output.mkdir(parents=True, exist_ok=True)
    profile = arguments.profile.resolve() if arguments.profile else None
    if profile:
        for required in ["java_bundle/lib/modules", "lib", "sources/config.json"]:
            if not (profile / required).exists():
                raise RuntimeError("Missing runtime profile artifact: " + str(profile / required))
    if os.uname().sysname != "Darwin" or os.uname().machine != "arm64":
        raise RuntimeError("An Apple Silicon Mac with Xcode is required")
    java = os.environ.get("KOTOTORO_JVM_BOOT_JDK") or subprocess.check_output(
        ["/usr/libexec/java_home", "-v", "24"], text=True).strip()
    version = subprocess.run([str(Path(java) / "bin/java"), "-version"], capture_output=True, text=True, check=True)
    if 'version "24.' not in version.stderr:
        raise RuntimeError("KOTOTORO_JVM_BOOT_JDK must point to JDK 24")
    env = dict(os.environ, JAVA_HOME=java, PATH=str(TOOLS / "bin") + ":" + java + "/bin:" + os.environ["PATH"])
    build_tool("m4", "m4.tar.xz", env)
    build_tool("autoconf", "autoconf.tar.xz", dict(env, M4=str(TOOLS / "bin/m4")))

    # A separate source tree prevents accidental reuse of the old preview's third-party patches.
    spec = spec_from_file_location("kototoro_openjdk", APP / "Scripts/openjdk-ios.py")
    adaptation = module_from_spec(spec)
    spec.loader.exec_module(adaptation)
    mobile_archive = download("mobile.tar.gz")
    source_root = WORK / "kototoro-openjdk"
    source_root.mkdir(exist_ok=True)
    mobile = source_root / ("mobile-" + PINS["openjdkRevision"])
    stamp = mobile / ".kototoro-patched"
    patch_version = hashlib.sha256((inspect.getsource(adaptation.patch) + inspect.getsource(adaptation.replace)).encode()).hexdigest()
    if not stamp.exists():
        if mobile.exists():
            raise RuntimeError("Unstamped source tree exists; inspect it before rebuilding: " + str(mobile))
        extract(mobile_archive, source_root)
        adaptation.patch(mobile)
        stamp.write_text(patch_version)
    if stamp.read_text() != patch_version:
        raise RuntimeError("Source patch revision differs from the current pins")
    adaptation.patch_platform_properties(mobile)

    support = WORK / ("libffi" if simulator else "libffi-device")
    ffi_archive = download("libffi.zip" if simulator else "libffi-device.zip")
    ffi_digest = hashlib.sha256(ffi_archive.read_bytes()).hexdigest()
    ffi_stamp = support / ".kototoro-archive-sha256"
    if not ffi_stamp.exists() or ffi_stamp.read_text() != ffi_digest:
        with zipfile.ZipFile(ffi_archive) as archive:
            archive.extractall(support)
        ffi_stamp.write_text(ffi_digest)
    ffi = WORK / ("libffi-arm64.a" if simulator else "libffi-device-arm64.a")
    if simulator:
        run(["xcrun", "lipo", "-thin", "arm64", support / "libffi.a", "-output", ffi])
    else:
        shutil.copy2(support / "libffi.a", ffi)
    sdk = subprocess.check_output(["xcrun", "--sdk", arguments.platform, "--show-sdk-path"], text=True).strip()
    mac_sdk = subprocess.check_output(["xcrun", "--sdk", "macosx", "--show-sdk-path"], text=True).strip()
    conf = "iossim-aarch64-zero-release" if simulator else "ios-aarch64-zero-release"
    flags = ("-target arm64-apple-ios17.0-simulator -mios-simulator-version-min=17.0" if simulator else
             "-target arm64-apple-ios17.0 -miphoneos-version-min=17.0")
    configuration = ["bash", "configure", "--with-jobs=4", "--with-conf-name=" + conf, "--disable-warnings-as-errors",
         "--with-build-jdk=" + str(linker_jdk()),
         "--openjdk-target=aarch64-macos-ios", "--with-sysroot=" + sdk,
         "--with-libffi-include=" + str(support / "include/ffi"), "--with-libffi-lib=" + str(support),
         "--with-extra-cflags=" + flags, "--with-extra-cxxflags=" + flags, "--with-extra-ldflags=" + flags,
         "--with-cups-include=" + mac_sdk + "/usr/include"]
    build = mobile / "build" / conf
    specification = build / "spec.gmk"
    configured = False
    if specification.exists():
        spec_text = specification.read_text()
        command = re.search(r"^CONFIGURE_COMMAND_LINE := (.*)$", spec_text, re.MULTILINE)
        configured = command is not None and shlex.split(command.group(1)) == configuration[2:] and (
            "BOOT_JDK := " + java + "\n" in spec_text
        )
    if not configured:
        run(configuration, cwd=mobile, env=env)
    run(["make", "LOG=info", "CONF=" + conf, "static-libs-image"], cwd=mobile, env=env)
    libraries = build / "images/static-libs/lib"
    native_libraries = [libraries / name for name in ["libverify.a", "libjava.a", "libzip.a", "libnet.a", "libnio.a", "libjimage.a"]]
    count = adaptation.generate_symbols(mobile, [libraries / "zero/libjvm.a"] + native_libraries)
    print("Retaining", count, "native OpenJDK exports", flush=True)
    run(["make", "LOG=info", "CONF=" + conf, "static-libs-image"], cwd=mobile, env=env)
    run(["libtool", "-static", "-o", output / "libkototoro-jvm.a", libraries / "zero/libjvm.a", ffi] +
        native_libraries)
    shutil.copytree(build / "jdk/include", output / "include", dirs_exist_ok=True)
    shutil.copytree(build / "jdk/include/ios", output / "include", dirs_exist_ok=True)

    if profile:
        if (profile / "boot-shims.jar").exists():
            raise RuntimeError("Legacy boot shim profile: regenerate with Kototoro's own shims")
        for name in ["java_bundle", "lib", "sources"]:
            shutil.copytree(profile / name, output / name, dirs_exist_ok=True)
        if not (profile / "runtime-origin.json").is_file():
            raise RuntimeError("Missing independently built profile provenance")
        shutil.copy2(profile / "runtime-origin.json", output / "runtime-origin.json")
        print(arguments.platform + " JVM preview ready:", output, flush=True)
        return

    run(["make", "LOG=info", "CONF=" + conf, "jdk.unsupported-java", "jdk.localedata-java", "jdk.charsets-java", "java.base-gendata"], cwd=mobile, env=env)
    java_image(mobile, build, output)
    (output / "runtime-origin.json").write_text(json.dumps({
        "openjdkRevision": PINS["openjdkRevision"], "adaptationSha256": patch_version,
        "platformAdaptationSha256": hashlib.sha256(
            inspect.getsource(adaptation.patch_platform_properties).encode()).hexdigest(),
        "modules": ["java.base", "java.xml", "java.logging", "jdk.unsupported", "jdk.localedata", "jdk.charsets"],
        "nativeExports": count,
    }, indent=2))
    run([ROOT / "gradlew", ":source-host:installDist", ":source-host:exportEmbeddedFixture", "--no-daemon"], cwd=ROOT, env=env)
    shutil.copytree(ROOT / "source-host/build/install/source-host/lib", output / "lib", dirs_exist_ok=True)
    fixture = ROOT / "source-host/build/embedded-fixture"
    shutil.copy2(fixture / "fixture-api.jar", output / "lib/fixture-api.jar")
    (output / "sources").mkdir(exist_ok=True)
    for name in ["runtime.jar", "config.json"]:
        shutil.copy2(fixture / name, output / "sources" / name)
    (output / "sources/preview.json").write_text(json.dumps({"label": "独立测试源，仅用于运行时验证"}, ensure_ascii=False))
    print(arguments.platform + " JVM preview ready:", output, flush=True)


if __name__ == "__main__":
    main()
